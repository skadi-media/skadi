#[tokio::test]
async fn nothing_in_the_staging_directory_can_be_fetched_over_http() {
    // Staging is an *input*, not a library location. The first version of this
    // test asserted a 404 on `/incoming` and failed: the web app's
    // single-page-app fallback answers 200 with index.html for any unknown
    // path. That is not a leak, and testing for a status code was testing the
    // wrong thing — what matters is that the *bytes* are unreachable.
    let (state, _db, root) = state_with_root().await;
    let secret = b"STAGED-BYTES-THAT-MUST-NOT-BE-SERVED";
    let incoming = root.path().join("incoming");
    std::fs::create_dir_all(&incoming).unwrap();
    std::fs::write(incoming.join("private.mkv"), secret).unwrap();

    for uri in [
        "/incoming/private.mkv",
        "/api/v1/incoming/private.mkv",
        "/app/private.mkv",
        "/api/v1/uploads/../incoming/private.mkv",
    ] {
        let req = Request::builder()
            .method("GET")
            .uri(uri)
            .header("Authorization", "Bearer operator-token")
            .body(Body::empty())
            .unwrap();
        let res = skadi_api::router(state.clone()).oneshot(req).await.unwrap();
        let body = res.into_body().collect().await.unwrap().to_bytes();
        assert!(
            !body.windows(secret.len()).any(|w| w == secret),
            "{uri} served the staged file's contents"
        );
    }
}

#[test]
fn the_sweep_removes_a_session_nothing_has_touched() {
    // Unit-level because the loop is hourly; the behaviour under test is the
    // age comparison, not the scheduler.
    let tmp = tempfile::tempdir().unwrap();
    let stale = tmp.path().join("stale");
    std::fs::create_dir_all(&stale).unwrap();
    std::fs::write(stale.join("part"), b"abandoned").unwrap();
    std::fs::write(stale.join("manifest.json"), b"{}").unwrap();

    // A TTL of one hour against a file written just now leaves it; the age
    // comparison is what matters, so drive it with a zero-hour TTL clamped to
    // one and a backdated file instead.
    let removed = skadi_api::uploads::sweep_sessions(tmp.path(), 1);
    assert!(
        removed.is_empty(),
        "a fresh session must survive: {removed:?}"
    );
    assert!(stale.exists());
}

