//! Upload sessions end to end (SKADI-T-0628).
//!
//! The mechanics that matter are the ones a flaky connection exercises:
//! resuming from the server's high-water mark, re-sending a chunk that already
//! landed, and refusing a chunk that would leave a hole. Each is tested
//! against the real router rather than the helper functions, because the bugs
//! here live in the wiring — an offset misread from a query string is not
//! something a unit test of `safe_filename` would ever catch.

use std::sync::Arc;

use axum::body::Body;
use axum::http::{Request, StatusCode};
use http_body_util::BodyExt;
use skadi_store::ConfigRepo;
use skadi_store::ConfigSource;
use tower::ServiceExt;

use skadi_api::{AppState, Config};
use skadi_testsupport::TestDb;

fn config() -> Config {
    Config {
        database_url: "sqlite://:memory:".into(),
        bind_addr: "127.0.0.1:0".parse().unwrap(),
        bearer_token: Some("operator-token".into()),
    }
}

async fn call(
    state: &Arc<AppState>,
    method: &str,
    uri: &str,
    body: Option<serde_json::Value>,
) -> (StatusCode, serde_json::Value) {
    let req = Request::builder()
        .method(method)
        .uri(uri)
        .header("Authorization", "Bearer operator-token");
    let req = match body {
        Some(b) => req
            .header("content-type", "application/json")
            .body(Body::from(b.to_string()))
            .unwrap(),
        None => req.body(Body::empty()).unwrap(),
    };
    let res = skadi_api::router(state.clone()).oneshot(req).await.unwrap();
    let status = res.status();
    let bytes = res.into_body().collect().await.unwrap().to_bytes();
    (
        status,
        serde_json::from_slice(&bytes).unwrap_or(serde_json::Value::Null),
    )
}

/// Send raw bytes at an offset, the way the browser will.
async fn put_chunk(
    state: &Arc<AppState>,
    id: &str,
    offset: u64,
    bytes: &[u8],
) -> (StatusCode, serde_json::Value) {
    let req = Request::builder()
        .method("PUT")
        .uri(format!("/api/v1/uploads/{id}/chunk?offset={offset}"))
        .header("Authorization", "Bearer operator-token")
        .header("content-type", "application/octet-stream")
        .body(Body::from(bytes.to_vec()))
        .unwrap();
    let res = skadi_api::router(state.clone()).oneshot(req).await.unwrap();
    let status = res.status();
    let body = res.into_body().collect().await.unwrap().to_bytes();
    (
        status,
        serde_json::from_slice(&body).unwrap_or(serde_json::Value::Null),
    )
}

/// A state whose `library.root` is a real directory, since that is where
/// uploads must land — see SKADI-I-0062 on why staging cannot be elsewhere.
async fn state_with_root() -> (Arc<AppState>, TestDb, tempfile::TempDir) {
    let db = TestDb::new_store_only().await;
    let dir = tempfile::tempdir().unwrap();
    db.store
        .set_config(
            "library.root",
            &dir.path().display().to_string(),
            ConfigSource::Runtime,
        )
        .await
        .unwrap();
    let state = AppState::new_full(config(), Some(db.store.clone()), vec![], vec![]);
    state.refresh_members().await;
    (state, db, dir)
}

/// A real WAV, generated by a canonical writer rather than hand-assembled.
///
/// The tests that run all the way to completion need bytes the probe can
/// actually read, because an upload now has to prove it is media before it can
/// be adopted (SKADI-T-0629). My first attempt at synthesising a WAV header
/// inline produced a file `lofty` refused — which is the check doing its job,
/// and a good reminder that "looks like a valid header" is not the same as
/// "a decoder accepts it". The fixture removes that guesswork from the test.
fn tiny_wav() -> Vec<u8> {
    include_bytes!("fixtures/tone.wav").to_vec()
}

fn sha256_hex(bytes: &[u8]) -> String {
    use sha2::{Digest, Sha256};
    let mut h = Sha256::new();
    h.update(bytes);
    h.finalize().iter().map(|b| format!("{b:02x}")).collect()
}

