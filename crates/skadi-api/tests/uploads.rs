#[tokio::test]
async fn one_contributor_cannot_touch_another_contributors_upload() {
    // Two people with the same role. Sharing a role is not sharing a session.
    let (state, _db, _root) = state_with_root().await;
    let alice = member_token(&state, "Alice", "contributor").await;
    let bob = member_token(&state, "Bob", "contributor").await;

    let (st, s) = call_as(
        &state,
        &alice,
        "POST",
        "/api/v1/uploads",
        Some(serde_json::json!({ "filename": "hers.mkv", "size_bytes": 50, "kind": "movie" })),
    )
    .await;
    assert_eq!(st, StatusCode::OK, "{s}");
    let id = s["id"].as_str().unwrap().to_string();

    // A 404 rather than a 403: Bob has no business learning which session ids
    // exist, and that distinction is exactly what the status code leaks.
    for (m, uri) in [
        ("GET", format!("/api/v1/uploads/{id}")),
        ("POST", format!("/api/v1/uploads/{id}/complete")),
        ("DELETE", format!("/api/v1/uploads/{id}")),
    ] {
        let (st, v) = call_as(&state, &bob, m, &uri, None).await;
        assert_eq!(st, StatusCode::NOT_FOUND, "{m} {uri}: {v}");
    }

    // And Alice's session is untouched.
    let (st, v) = call_as(
        &state,
        &alice,
        "GET",
        &format!("/api/v1/uploads/{id}"),
        None,
    )
    .await;
    assert_eq!(st, StatusCode::OK, "{v}");
}

