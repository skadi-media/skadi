#[tokio::test]
async fn a_file_sent_in_chunks_arrives_whole() {
    let (state, _db, root) = state_with_root().await;
    let payload = tiny_wav();

    let s = open_audio(&state, "Some Book.wav", payload.len()).await;
    let id = s["id"].as_str().unwrap().to_string();
    assert_eq!(s["received_bytes"], 0);

    for part in payload.chunks(1000) {
        let have = call(&state, "GET", &format!("/api/v1/uploads/{id}"), None)
            .await
            .1["received_bytes"]
            .as_u64()
            .unwrap();
        let (st, v) = put_chunk(&state, &id, have, part).await;
        assert_eq!(st, StatusCode::OK, "{v}");
    }

    let (st, done) = call(
        &state,
        "POST",
        &format!("/api/v1/uploads/{id}/complete"),
        None,
    )
    .await;
    assert_eq!(st, StatusCode::OK, "{done}");

    // The bytes on disk are the bytes that were sent, in order.
    let path = done["path"].as_str().unwrap();
    assert!(
        path.starts_with(&root.path().display().to_string()),
        "staging must be under the library root, got {path}"
    );
    assert_eq!(std::fs::read(path).unwrap(), payload);
}

#[tokio::test]
async fn re_sending_a_chunk_that_already_landed_is_not_an_error() {
    // The case this exists for: the client sent a chunk, the server wrote it,
    // and the response was lost. The client must be able to re-send without
    // either failing or appending the same bytes twice.
    let (state, _db, _root) = state_with_root().await;
    let s = open(&state, "retry.mkv", 200).await;
    let id = s["id"].as_str().unwrap().to_string();

    let (st, _) = put_chunk(&state, &id, 0, &[7u8; 100]).await;
    assert_eq!(st, StatusCode::OK);
    let (st, v) = put_chunk(&state, &id, 0, &[7u8; 100]).await;
    assert_eq!(st, StatusCode::OK, "a retry must be accepted: {v}");
    assert_eq!(
        v["received_bytes"], 100,
        "the retry must not have been appended a second time"
    );
}

